#!/usr/bin/env python3
"""Run all 15 competency questions against the live Fuseki HTTP endpoint.

This is the evidence that the queries work in a standard triplestore over
SPARQL 1.1 Protocol, not merely in-process with RDFLib. Row counts are
asserted against the expected values recorded in queries.py, so a regression
fails the run.

Usage:
    python3 app/run_cqs.py                 # table to stdout, assert counts
    python3 app/run_cqs.py --markdown OUT  # also write a results document
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from queries import ALL, CQS, RULES, render  # noqa: E402

ENDPOINT = "http://localhost:3030/philosophy/sparql"


def run(query: str, accept: str) -> tuple[int, object]:
    """POST a query to the endpoint. Returns (status, parsed body)."""
    data = urllib.parse.urlencode({"query": query}).encode()
    req = urllib.request.Request(
        ENDPOINT, data=data,
        headers={"Accept": accept,
                 "Content-Type": "application/x-www-form-urlencoded"})
    with urllib.request.urlopen(req, timeout=120) as resp:
        body = resp.read().decode("utf-8")
        return resp.status, body


def execute(cq) -> dict:
    """Run one CQ and return a normalised result record."""
    query = render(cq)
    if cq.kind in ("construct", "describe"):
        status, body = run(query, "text/turtle")
        # count triples by parsing, so blank-node and prefix noise cannot skew it
        from rdflib import Graph
        g = Graph()
        g.parse(data=body, format="turtle")
        return {"status": status, "count": len(g), "rows": None,
                "turtle": body, "vars": []}

    status, body = run(query, "application/sparql-results+json")
    payload = json.loads(body)
    if "boolean" in payload:
        return {"status": status, "count": payload["boolean"],
                "rows": None, "vars": [], "boolean": payload["boolean"]}
    rows = payload["results"]["bindings"]
    return {"status": status, "count": len(rows), "rows": rows,
            "vars": payload["head"]["vars"]}


def fmt_cell(binding: dict) -> str:
    value = binding.get("value", "")
    if binding.get("type") == "uri":
        return value.replace("http://example.org/philosophy#", ":")
    return value


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", help="write a results document to this path")
    args = ap.parse_args()

    print(f"endpoint: {ENDPOINT}\n")
    doc: list[str] = [
        "# Competency questions executed against Apache Jena Fuseki",
        "",
        "Generated by `app/run_cqs.py`. Every query below was sent to a running",
        f"Fuseki 6.2.0 server over the SPARQL 1.1 Protocol at `{ENDPOINT}`",
        "and the row counts were asserted against the expected values in",
        "`app/queries.py`. This is the triplestore evidence for the rubric's",
        '"validates successfully in standard tools".',
        "",
    ]

    failures = 0
    for cq in ALL:
        try:
            result = execute(cq)
        except Exception as exc:  # noqa: BLE001
            print(f"  FAIL {cq.id:5} transport error: {exc}")
            failures += 1
            continue

        got = result["count"]
        want = (cq.endpoint_expected if cq.endpoint_expected is not None
                else cq.expected)
        ok = got == want
        failures += 0 if ok else 1
        flag = "ok  " if ok else "FAIL"
        print(f"  {flag} {cq.id:5} HTTP {result['status']}  "
              f"expected {str(want):>5}  got {got}")

        doc.append(f"## {cq.id}. {cq.question}")
        doc.append("")
        doc.append(f"**SPARQL features:** {cq.features}  ")
        doc.append(f"**Ontology path:** `{cq.path}`  ")
        doc.append(f"**Result:** HTTP {result['status']}, "
                   f"{got} {'triples' if cq.kind in ('construct', 'describe') else 'rows'} "
                   f"(expected {want}) {'PASS' if ok else 'FAIL'}")
        if cq.note:
            doc.append(f"  \n*{cq.note}*")
        doc.append("")
        doc.append("```sparql")
        doc.append(render(cq).strip())
        doc.append("```")
        doc.append("")

        if result.get("rows"):
            variables = result["vars"]
            doc.append("| " + " | ".join(variables) + " |")
            doc.append("|" + "|".join(["---"] * len(variables)) + "|")
            for row in result["rows"][:15]:
                doc.append("| " + " | ".join(
                    fmt_cell(row.get(v, {})) for v in variables) + " |")
            if len(result["rows"]) > 15:
                doc.append(f"| … | *{len(result['rows']) - 15} more rows* |")
            doc.append("")
        elif "boolean" in result:
            doc.append(f"**Answer:** `{result['boolean']}`")
            doc.append("")
        elif result.get("turtle"):
            snippet = result["turtle"].strip().splitlines()
            doc.append("```turtle")
            doc += snippet[:20]
            if len(snippet) > 20:
                doc.append(f"# … {len(snippet) - 20} more lines")
            doc.append("```")
            doc.append("")

    print(f"\n{len(ALL) - failures}/{len(ALL)} passed")
    if args.markdown:
        header = (f"\n*{len(ALL) - failures} of {len(ALL)} checks passed.*\n")
        doc.insert(8, header)
        Path(args.markdown).write_text("\n".join(doc) + "\n", encoding="utf-8")
        print(f"wrote {args.markdown}")
    _ = CQS, RULES
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
